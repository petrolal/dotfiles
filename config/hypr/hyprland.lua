-- This file only sets up the handful of values every conf/ module below
-- shares (mainMod, imp_bin -- left as plain globals, not `local`, since
-- dofile() runs each module in this same Lua global environment) and then
-- loads each module in the order Hyprland needs them applied. See
-- config/hypr/conf/ for the actual settings/keybinds/autostart, split out
-- by concern (mirrors ML4W's dotfiles config/hypr/conf/ layout -- see
-- conf/keybindings.lua's header comment and docs/migration_plan.md).

hl.config({ autogenerated = false })

mainMod = "SUPER"
imp_bin = (function()
    local p = (os.getenv("HOME") or "") .. "/dotfiles/bin/imp"
    local f = io.open(p, "r")
    if f then f:close(); return p end
    return "imp"
end)()

local CONF = (os.getenv("HOME") or "") .. "/dotfiles/config/hypr/conf/"

dofile(CONF .. "input.lua")
dofile(CONF .. "monitors.lua")
dofile(CONF .. "autostart.lua")
-- Declared before keybindings.lua because that module's astroland
-- keybinds (mod+ctrl+shift+S, mod+Escape) need hl.plugin.astroland loaded
-- first.
dofile(CONF .. "astroland.lua")
dofile(CONF .. "env.lua")
dofile(CONF .. "cursor.lua")
dofile(CONF .. "keybindings.lua")
dofile(CONF .. "window-rules.lua")
