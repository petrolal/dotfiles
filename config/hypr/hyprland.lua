-- This file only sets up the handful of values every conf/ module below
-- shares (mainMod, imp_bin, DOTFILES_DIR -- left as plain globals, not
-- `local`, since dofile() runs each module in this same Lua global
-- environment) and then loads each module in the order Hyprland needs them
-- applied. See config/hypr/conf/ for the actual settings/keybinds/
-- autostart, split out by concern (mirrors ML4W's dotfiles
-- config/hypr/conf/ layout -- see conf/keybindings.lua's header comment and
-- docs/migration_plan.md).

hl.config({ autogenerated = false })

mainMod = "SUPER"

-- Mirrors DotfilePaths.findDotfilesRoot()'s $DOTFILES_DIR override (see
-- src/main/kotlin/dev/petrolal/dotfiles/core/DotfilePaths.kt) so a repo
-- cloned somewhere other than ~/dotfiles doesn't silently break this half
-- of the config too.
DOTFILES_DIR = os.getenv("DOTFILES_DIR") or ((os.getenv("HOME") or "") .. "/dotfiles")

imp_bin = (function()
    local p = DOTFILES_DIR .. "/bin/imp"
    local f = io.open(p, "r")
    if f then f:close(); return p end
    return "imp"
end)()

local CONF = DOTFILES_DIR .. "/config/hypr/conf/"

dofile(CONF .. "input.lua")
dofile(CONF .. "monitors.lua")
dofile(CONF .. "autostart.lua")
dofile(CONF .. "env.lua")
dofile(CONF .. "cursor.lua")
dofile(CONF .. "keybindings.lua")
dofile(CONF .. "window-rules.lua")
