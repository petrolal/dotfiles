-- Keybinding scheme follows ML4W's dotfiles (mylinuxforwork/dotfiles,
-- config/hypr/conf/keybindings/default.lua) at the user's request --
-- same key combinations and intent, pointed at apps actually installed on
-- this NixOS host instead of ML4W's own script/quickshell ecosystem (which
-- isn't installed here). ML4W features with no local equivalent (cliphist,
-- dock, sidebar/calendar widgets, theme switcher, hyprsunset, overview) are
-- left out rather than bound to nothing. See docs/migration_plan.md.
--
-- XFCE has been fully decommissioned (docs/migration_plan.md section 0A):
-- every binding below that used to shell out to an xfce4-* binary now
-- targets a real standalone package (nixos/modules/packages.nix) instead,
-- and the status bar is AGS, not Waybar.

hl.config({ autogenerated = false })

---------------
---- INPUT ----
---------------
-- Never set before, so Hyprland fell back to plain "English (US)" with no
-- accent support at all. Mirrors nixos/modules/desktop.nix's
-- `console.keyMap = "us-acentos"` (the TTY-only keymap, which this doesn't
-- cover) on the Wayland side: physical US keyboard, dead-key-composed
-- accents (XKB's "us(intl)" variant) for typing Portuguese.
hl.config({
    input = {
        kb_layout = "us",
        kb_variant = "intl",
        touchpad = {
            disable_while_typing = false,
        },
    },
    misc = {
        disable_hyprland_logo = true,
        disable_splash_rendering = true,
        background_color = 0x000000,
    },
    decoration = {
        screen_shader = os.getenv("HOME") .. "/.config/hypr/vhs.frag",
    },
})

-- Declared up top (rather than down in ---- KEYBINDINGS ---- where it used
-- to live) because the ASTROLAND block below also needs it, and that block
-- runs before the keybindings section.
local mainMod = "SUPER"

------------------
---- MONITORS ----
------------------
-- Automatically detect and configure any connected display (laptop screen,
-- external HDMI, DisplayPort, etc.) with its best native resolution and
-- refresh rate, while enforcing integer 1:1 scale (scale = 1) so it never
-- blurs or shrinks the desktop with fractional scaling.
hl.monitor({
    output   = "",
    mode     = "preferred",
    position = "auto",
    scale    = 1,
})

-------------------
---- AUTOSTART ----
-------------------
hl.on("hyprland.start", function ()
  hl.exec_cmd("hyprpaper")
  -- Idle-triggered screensaver -- see config/hypr/hypridle.conf.
  hl.exec_cmd("hypridle")
  -- Quickshell handles Astroland overlays: battery/clock info overlay,
  -- robot notification popups, lockscreen, and screensaver.
  hl.exec_cmd("qs")
  -- Background notification logger for Tofi notification center
  hl.exec_cmd(os.getenv("HOME") .. "/.config/scripts/notif-logger.sh")
end)

-------------------
---- ASTROLAND ----
-------------------
-- Official Astroland Hyprland plugin (libastroland.so).
-- To build: in nix-shell / with cmake, run `cmake -B build && cmake --build build`
-- inside astroland/plugin/.
hl.plugin.load(os.getenv("HOME") .. "/dotfiles/astroland/plugin/build/libastroland.so")

local function file_exists(path)
    local file = io.open(path, "r")
    if file then
        file:close()
        return true
    end
    return false
end

if hl.plugin.astroland ~= nil then
    hl.config({
        general = { layout = "astrolayout" },
        plugin = {
            astroland = {
                spawn_moons = true,
                -- Cosmetic swap: moons render as a looping animated GIF
                -- instead of their static sprite, and bullets bounce off
                -- them instead of damaging them. Off by default, same as
                -- the original.
                loon_moons = false,
            },
        },
    })

    -- mod+ctrl+shift+S to save the current ship/bullet/moon state to
    -- ~/.config/hypr/save.lua
    hl.bind(mainMod .. " + CTRL + SHIFT + S", function()
        hl.plugin.astroland.save()
    end, { description = "Save astroland game state" })

    -- mod+Escape to unfocus all windows and immediately pilot the ship
    hl.bind(mainMod .. " + Escape", function()
        hl.plugin.astroland.unfocus()
    end, { description = "Unfocus windows to pilot astroland ship" })

    -- Load the save file (if any) once Hyprland's ready, same as the original.
    hl.on("hyprland.start", function()
        local savePath = os.getenv("HOME") .. "/.config/hypr/save.lua"
        if file_exists(savePath) then
            dofile(savePath)
        end
    end)
end

-------------------------------
---- ENVIRONMENT VARIABLES ----
